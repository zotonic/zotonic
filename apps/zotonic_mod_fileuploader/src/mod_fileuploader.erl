%% @doc Supervisor callback, initialize the children.
init([]) ->
    SupFlags = #{
        strategy => simple_one_for_one,
        intensity => 10,
        period => 5
    },
    ChildSpecs = [
        #{
            id => uploader,
            start => {z_fileuploader, start_link, []},
            shutdown => brutal_kill,
            restart => temporary
        }
    ],
    {ok, {SupFlags, ChildSpecs}}.
