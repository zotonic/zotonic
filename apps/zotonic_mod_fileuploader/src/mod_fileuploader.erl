-module(mod_fileuploader).
-moduledoc(#{
    zotonic_keywords => ["reference", "frontend_developer", "module", "file_uploads", "javascript", "upload"]
}).
-moduledoc("
Upload files using a parallel web worker.

This module provides a web worker and server logic to quickly upload files.

The web worker sends files in 128KB parts to the server, the server recombines all parts to a single file. The web
worker is using multiple parallel uploaders to make optimal use of the available bandwidth.

Files are sent to the webworker on the topic `model/fileuploader/post/new`:


```javascript
let f = document.getElementById(\"upload_file\").files[0];

let msg = {
    files: [
        {
            name: \"resultname\",             // The name used in the ready message
            upload: \"WZkhXoaMwrK2StUHmdpp\", // Unique name to register the upload process. It's generated by the server if undefined
            file: f                         // Must be a File object
        }
    ],

    start_topic: \"bridge/origin/foo\", // Receives the upload metadata when the upload starts

    ready_msg: {
        foo: \"bar\",                 // Anything you want to send if all files are uploaded
        files: []                   // This will be set by the worker
    },
    ready_topic: \"bridge/origin/foo/bar\",

    progress_msg: {
        form_id: \"some-element-id\",
        is_auto_unmask: true,
        percentage: 0               // Will be set by the uploader, 100 when ready
    },
    progress_topic: \"zotonic-transport/progress\"
};
cotonic.broker.publish(\"model/fileuploader/post/new\", msg);
```

The files received with the `ready_msg` on the `ready_topic` will be:


```javascript
{
    name: \"resultname\",             // Name provided in the upload
    upload: \"WZkhXoaMwrK2StUHmdpp\"  // Unique name to use with z_fileuploader:status/1
}
```

An upload can be canceled by publishing the topic `model/fileuploader/post/delete/+name`, where the name is the unique
name generated by the server.

Admin drop zones
----------------

The admin uses `_fileuploader_dropzone.tpl` for independent uploads. Its
`upload_options` map supports `subject_id` and `predicate` for connections,
`id` and `is_medium` for a single-file replacement, `is_published` for creation,
and `refresh` for offering a media-list refresh after a batch.
Normal media and edge ACL checks still apply when the uploaded files are stored.

Dialog elements with `data-fileuploader-input` only populate their native file
input, retaining the existing form metadata and submit postback. Independent
pickers use `nosubmit` so they are not included in a surrounding edit form.
Contextual uploads send one file at a time in selection order. Each file shows
transfer progress followed by a processing state and its server-confirmed result.
Failed files can be retried without re-uploading successful files. A saved file
whose connection failed is reported separately and is not eligible for upload retry.
Completion is reported after media processing on
`model/fileuploader/event/admin-complete` with `target`, `upload_id`, `failed`, and
`saved` fields. Attempt identifiers prevent delayed events from changing a retry's
result. The overview keeps results visible until the user refreshes the list.

The shared Upload dialog opts in with `data-fileuploader-feedback`. Its signed
form postback and metadata are retained, including when retrying a failed file.
A leave-page guard stays active through transfer and server-side processing.

Cancel remaining uploads marks queued files as cancelled and sends
`model/fileuploader/post/cancel` with the active `target` and `upload_id`.
The worker aborts block transfers, removes temporary sessions (including late
session replies), and acknowledges on `model/fileuploader/event/cancelled`.
Once a request has been submitted for saving, it cannot be cancelled; its result
is awaited and already-saved media is retained. Cancellation is not upload failure.

Size and input accept restrictions are checked before submitting a selection.
The worker also calls `m_fileuploader`'s `validate` endpoint before hashing or
transferring files, so current account MIME and size restrictions are checked
on the server. These checks do not replace the ACL checks when saving media.

