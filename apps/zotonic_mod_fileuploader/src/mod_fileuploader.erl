%% @doc Upload event from the UI.
event(#z_msg_v1{ data = Data }, Context) ->
    ExtraData = proplists:get_value(<<"data">>, Data),
    Target = proplists:get_value(<<"target">>, Data, <<"body">>),
    Files = proplists:get_value(<<"fileuploader">>, Data, []),
    Context0 = z_context:set(fileuploader_saved, false,
        z_context:set(fileuploader_failed, false, Context)),
    Context1 = case {ExtraData, Files} of
        {#{ <<"is_medium">> := true }, [_, _ | _]} ->
            lists:foreach(fun
                (#{ <<"upload">> := Name }) -> z_fileuploader:stop(Name);
                (_) -> ok
            end, Files),
            upload_error(?__("Please choose one file only.", Context), Context0);
        _ -> upload_files(Files, ExtraData, Context0)
    end,
    Failed = z_context:get(fileuploader_failed, Context1),
    z_mqtt:publish([<<"~client">>, <<"model">>, <<"fileuploader">>, <<"event">>, <<"admin-complete">>],
        #{ target => Target, failed => Failed,
           upload_id => proplists:get_value(<<"upload_id">>, Data),
           saved => z_context:get(fileuploader_saved, Context1) }, Context1),
    Context2 = z_render:wire({unmask, [ {target, Target} ]}, Context1),
    case {maybe_get(<<"refresh">>, ExtraData, false), Failed} of
        {true, false} -> z_render:wire({reload, []}, Context2);
        _ -> Context2
    end.

%% The worker completes files in transfer order; numbered field names retain drop order.
upload_files(Files, ExtraData, Context) ->
    Ordered = lists:sort(fun(A, B) ->
        maps:get(<<"name">>, A, <<>>) =< maps:get(<<"name">>, B, <<>>)
    end, Files),
    lists:foldl(
        fun
            (#{<<"media_upload_token">> := Token} = Reuse, Ctx) when is_binary(Token) ->
                case z_media_upload:materialize(Reuse, Ctx) of
                    {ok, #upload{filename=Filename, tmpfile=Temp}} ->
                        do_upload({ok, #{name => <<>>, is_complete => true,
                            filename => Filename, uploaded_file => Temp}}, ExtraData, Ctx);
                    Error -> do_upload(Error, ExtraData, Ctx)
                end;
            (#{ <<"upload">> := Upload }, Ctx) ->
                do_upload(z_fileuploader:status(Upload), ExtraData, Ctx)
        end,
        Context,
        Ordered).

do_upload({ok, #{ is_complete := true } = Status}, #{ <<"id">> := Id, <<"is_medium">> := true }, Context) ->
    #{
        name := Name,
        filename := Filename,
        uploaded_file := TmpFile
    } = Status,
    ?LOG_DEBUG(#{
        in => zotonic_mod_fileuploader,
        text => <<"Upload finished with complete file - medium update">>,
        result => ok,
        filename => Filename,
        tmp_file => TmpFile
    }),
    RscProps = #{
        <<"original_filename">> => Filename
    },
    MediaContext = z_context:set(admin_media_update_id, m_rsc:rid(Id, Context), Context),
    Context1 = case m_media:replace_file(TmpFile, Id, RscProps, [], MediaContext) of
        {ok, _UpdatedId} ->
            F = z_html:escape(Filename),
            z_render:growl([ ?__("Uploaded", Context), " ", F ], Context);
        {error, _} ->
            F = z_html:escape(Filename),
            upload_error([ ?__("Could not upload", Context), " ", F ], Context)
    end,
    z_fileuploader:stop(Name),
    Context1;
do_upload({ok, #{ is_complete := true } = Status}, Data, Context) ->
    #{
        name := Name,
        filename := Filename,
        uploaded_file := TmpFile
    } = Status,
    ?LOG_DEBUG(#{
        in => zotonic_mod_fileuploader,
        text => <<"Upload finished with complete file - medium creation">>,
        result => ok,
        filename => Filename,
        tmp_file => TmpFile
    }),
    RscProps = #{
        <<"is_published">> => z_convert:to_bool(maybe_get(<<"is_published">>, Data, true)),
        <<"original_filename">> => Filename,
        <<"is_dependent">> => z_convert:to_bool( maybe_get(<<"is_dependent">>, Data, false) )
    },
    RscProps1 = rsc_props_from_data(RscProps, Data, Context),
    Context1 = case m_media:insert_file(TmpFile, RscProps1, [], Context) of
        {ok, RscId} ->
            F = z_html:escape(Filename),
            case maybe_edge(RscId, Data, Context) of
                {error, _} ->
                    upload_error([ ?__("Uploaded, but could not connect", Context), " ", F ],
                        z_context:set(fileuploader_saved, true, Context));
                _ ->
                    z_render:growl([ ?__("Uploaded", Context), " ", F ], Context)
            end;
        {error, _} ->
            F = z_html:escape(Filename),
            upload_error([ ?__("Could not upload", Context), " ", F ], Context)
    end,
    z_fileuploader:stop(Name),
    Context1;
do_upload({ok, #{ is_complete := false, filename := Filename, uploaded_file := TmpFile }}, _Data, Context) ->
    ?LOG_ERROR(#{
        in => zotonic_mod_fileuploader,
        text => <<"Upload finished with incomplete file">>,
        result => error,
        reason => incomplete,
        filename => Filename,
        tmp_file => TmpFile
    }),
    upload_error(?__("The file upload is incomplete.", Context), Context);
do_upload({error, Reason}, _Data, Context) ->
    ?LOG_ERROR(#{
        in => zotonic_mod_fileuploader,
        text => <<"Error uploading file">>,
        result => error,
        reason => Reason
    }),
    upload_error(?__("Error uploading the file.", Context), Context).

upload_error(Text, Context) ->
    z_render:growl_error(Text, z_context:set(fileuploader_failed, true, Context)).

maybe_get(K, M, D) when is_map(M) -> maps:get(K, M, D);
maybe_get(_, _, D) -> D.

rsc_props_from_data(RscProps, #{ <<"subject_id">> := Id }, Context) ->
    RscProps#{
        <<"content_group_id">> => m_rsc:p(Id, content_group_id, Context)
    };
rsc_props_from_data(RscProps, #{ <<"object_id">> := Id }, Context) ->
    RscProps#{
        <<"content_group_id">> => m_rsc:p(Id, content_group_id, Context)
    };
rsc_props_from_data(RscProps, _Data, _Context) ->
    RscProps.

maybe_edge(RscId, #{ <<"subject_id">> := Id } = Data, Context) ->
    Predicate = maps:get(<<"predicate">>, Data, <<"relation">>),
    m_edge:insert(Id, Predicate, RscId, Context);
maybe_edge(RscId, #{ <<"object_id">> := Id } = Data, Context) ->
    Predicate = maps:get(<<"predicate">>, Data, <<"relation">>),
    m_edge:insert(RscId, Predicate, Id, Context);
maybe_edge(_RscId, _Data, _Context) ->
    ok.


%% @doc Start the simple_one_for_one supervisor for the file upload processes.
start_link(Args) ->
    jsxrecord:load_records(z_fileuploader_recorddefs),
    {context, Context} = proplists:lookup(context, Args),
    SupName = z_utils:name_for_site(?MODULE, Context),
    supervisor:start_link({local, SupName}, ?MODULE, []).


%% @doc Start a file uploader.
-spec start_child( Filename :: binary(), Size :: non_neg_integer(), Context :: z:context() ) -> {ok, map()} | {error, term()}.
start_child(Filename, Size, Context) ->
    start_child(z_ids:id(), Filename, Size, Context).

%% @doc Start a file uploader.
-spec start_child( Name :: binary(), Filename :: binary(), Size :: non_neg_integer(), Context :: z:context() ) -> {ok, map()} | {error, term()}.
start_child(Name, Filename, Size, Context) ->
    SupName = z_utils:name_for_site(?MODULE, Context),
    ContextSpawn = z_context:prune_for_spawn(Context),
    case supervisor:start_child(SupName, [Name, Filename, Size, ContextSpawn]) of
        {ok, Pid} ->
            z_fileuploader:status(Pid);
        {error, _} = Error ->
            Error
    end.

%% @doc Replace all #fileuploader{} records with #upload{} and the uploaded file.
observe_validate_query_args(#validate_query_args{}, {ok, Qs}, _Context) ->
    lists:foldr(
        fun
            ({K, #fileuploader{ name = Name }}, {ok, Acc}) ->
                case z_fileuploader:status(Name) of
                    {ok, #{
                        is_complete := true,
                        filename := Filename,
                        uploaded_file := TmpFile
                    }} ->
                        {ok, {MonitorPid, NewTmpFile}} = z_tempfile:monitored_new(),
                        ok = file:rename(TmpFile, NewTmpFile),
                        z_fileuploader:stop(Name),
                        Upload = #upload{
                            filename = Filename,
                            tmpfile = NewTmpFile,
                            tmpmonitor = MonitorPid,
                            mime = undefined,
                            data = undefined
                        },
                        {ok, [ {K, Upload} | Acc ]};
                    {ok, #{
                        is_complete := false
                    }} ->
                        {error, file_incomplete};
                    {error, _} ->
                        {error, file_not_found}
                end;
            (KV, {ok, Acc}) ->
                {ok, [ KV | Acc ]};
            (_, {error, _} = Err) ->
                Err
        end,
        {ok, []},
        Qs);
observe_validate_query_args(#validate_query_args{}, {error, _} = Error, _Context) ->
    Error.

